"""Local-only UI regression: calendar, detail edits and manual financial records."""
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1440,'height':1000})
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8010/web/')
 assert page.locator('.calendar tbody tr').count()==40
 page.locator('[data-cell="TEST-KL-R1"]').first.click()
 page.locator('#order-form [name=guest]').fill('TEST Finance A')
 page.locator('#order-form [name=end]').fill('2027-01-12')
 page.locator('#order-form [name=nightly]').fill('123.45')
 page.locator('#order-form [name=source]').select_option('booking')
 page.locator('#order-form button.primary').click()
 assert page.locator('.calendar-booking').count()==2
 page.locator('.calendar-booking').first.click()
 assert '246.90' in page.locator('.folio-grid').inner_text()
 page.locator('#edit-form [name=end]').fill('2027-01-13')
 page.locator('#edit-form [name=notes]').fill('TEST late arrival')
 page.locator('#edit-form button.primary').click()
 assert '370.35' in page.locator('.folio-grid').inner_text()
 page.locator('#payment-form [name=amount]').fill('100')
 page.locator('#payment-form button.primary').click()
 assert '270.35' in page.locator('.folio-grid').inner_text()
 page.locator('#payment-form [name=kind]').select_option('deposit_in')
 page.locator('#payment-form [name=amount]').fill('50')
 page.locator('#payment-form button.primary').click()
 page.locator('#payment-form [name=kind]').select_option('refund')
 page.locator('#payment-form [name=amount]').fill('100.01')
 page.locator('#payment-form button.primary').click()
 assert '超过' in page.locator('#detail-error').inner_text()
 page.locator('#cancel-form [name=reason]').fill('TEST cancellation')
 page.locator('#cancel-form [name=finalCharge]').fill('0')
 page.locator('#cancel-form button').click()
 assert '已取消' in page.locator('#detail-body').inner_text()
 assert page.locator('.calendar-booking').count()==0
 page.locator('#payment-form [name=kind]').select_option('refund')
 page.locator('#payment-form [name=amount]').fill('100')
 page.locator('#payment-form button.primary').click()
 page.locator('#payment-form [name=kind]').select_option('deposit_out')
 page.locator('#payment-form [name=amount]').fill('50')
 page.locator('#payment-form button.primary').click()
 page.locator('#detail-close').click()
 with page.expect_download() as info:page.locator('#export').click()
 assert info.value.suggested_filename.endswith('.csv')
 for lang in ['en','ms','zh']:
  page.locator('#language').select_option(lang)
  page.locator('#new').click()
  assert page.locator('#order-form [name=source] option[value=direct]').inner_text() in ['Direct','Terus','直接预订']
  page.locator('#close').click()
 # Populate a visible cross-day booking to capture the working calendar.
 page.locator('[data-cell="TEST-KL-R2"]').first.click()
 page.locator('#order-form [name=guest]').fill('TEST Apartment Stay')
 page.locator('#order-form [name=end]').fill('2027-01-14')
 page.locator('#order-form [name=nightly]').fill('180')
 page.locator('#order-form button.primary').click()
 page.screenshot(path='/workspace/codex-pan/pms/artifacts/calendar-v03.png',full_page=True)
 page.set_viewport_size({'width':390,'height':844})
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 page.locator('.calendar-booking').first.click()
 assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
 assert not errors,errors
 browser.close()
 print('PASS: calendar click-create, detail editing, cents, refunds, deposit return, cancellation, CSV, languages and mobile dialog')
